const LANGUAGES = { en: 'English', hi: 'हिन्दी', te: 'తెలుగు' };
const INDEX = { hi: 0, te: 1 };

// The text in the other language, or the same text when there is no entry. Spaces around the text are kept.
function translate(text, lang) {
  if (!Object.prototype.hasOwnProperty.call(INDEX, lang)) return text;
  const key = String(text).trim();
  const entry = key && Object.prototype.hasOwnProperty.call(ENTRIES, key) ? ENTRIES[key] : null;
  return entry ? String(text).replace(key, entry[INDEX[lang]]) : text;
}

if (typeof module !== 'undefined' && module.exports) module.exports = { ENTRIES, LANGUAGES, translate };

// ---------------------------------------------------------------- in the browser: apply to the page
if (typeof document !== 'undefined') {
  (() => {
    const ATTRIBUTES = ['placeholder', 'title', 'aria-label', 'alt'];
    const originalText = new WeakMap(); // text node -> the English it had
    const originalAttrs = new WeakMap(); // element -> { attribute: English }
    let lang = 'en';
    try { lang = localStorage.getItem('pc_lang') || 'en'; } catch { /* storage blocked: English */ }
    if (!LANGUAGES[lang]) lang = 'en';
    let applying = false;

    function applyTo(root) {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
      for (let node = walker.currentNode; node; node = walker.nextNode()) {
        if (node.nodeType === Node.TEXT_NODE) {
          const parent = node.parentNode && node.parentNode.nodeName;
          if (parent === 'SCRIPT' || parent === 'STYLE' || parent === 'TEXTAREA') continue;
          const base = originalText.has(node) ? originalText.get(node) : node.data;
          const next = lang === 'en' ? base : translate(base, lang);
          if (next !== node.data) {
            if (!originalText.has(node)) originalText.set(node, base);
            node.data = next;
          }
        } else if (node.nodeType === Node.ELEMENT_NODE && node.hasAttributes()) {
          for (const name of ATTRIBUTES) {
            if (!node.hasAttribute(name)) continue;
            const saved = originalAttrs.get(node) || {};
            const base = name in saved ? saved[name] : node.getAttribute(name);
            const next = lang === 'en' ? base : translate(base, lang);
            if (next !== node.getAttribute(name)) {
              saved[name] = base;
              originalAttrs.set(node, saved);
              node.setAttribute(name, next);
            }
          }
        }
      }
    }

    function run(root) {
      if (applying) return;
      applying = true;
      try { applyTo(root); } finally { applying = false; }
    }

    function setLanguage(next) {
      if (!LANGUAGES[next]) return;
      lang = next;
      try { localStorage.setItem('pc_lang', next); } catch { /* storage blocked */ }
      document.documentElement.lang = next;
      const select = document.getElementById('lang-select');
      if (select) select.value = next;
      run(document.body);
    }

    new MutationObserver((records) => {
      if (applying || lang === 'en') return;
      applying = true;
      try {
        for (const r of records) for (const added of r.addedNodes) if (added.nodeType === Node.ELEMENT_NODE || added.nodeType === Node.TEXT_NODE) {
          if (added.nodeType === Node.TEXT_NODE) {
            const base = originalText.has(added) ? originalText.get(added) : added.data;
            const next = translate(base, lang);
            if (next !== added.data) { originalText.set(added, base); added.data = next; }
          } else applyTo(added);
        }
      } finally { applying = false; }
    }).observe(document.body, { childList: true, subtree: true });

    window.I18N = { setLanguage, translate: (t) => translate(t, lang), get language() { return lang; }, languages: LANGUAGES };
    document.addEventListener('DOMContentLoaded', () => {
      const select = document.getElementById('lang-select');
      if (select) {
        select.value = lang;
        select.addEventListener('change', () => setLanguage(select.value));
      }
      document.documentElement.lang = lang;
      if (lang !== 'en') run(document.body);
    });
  })();
}
